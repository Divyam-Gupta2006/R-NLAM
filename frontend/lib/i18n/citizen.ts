export const DICTS: Record<Lang, Dict> = { en, hi, mr };

/** Look up a key and fill {placeholders}. Unknown keys fall back to English, then the key itself. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const d = DICTS[lang] as Record<string, string>;
  const raw = d[key] ?? (en as Record<string, string>)[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] === undefined ? `{${k}}` : String(vars[k]))) : raw;
}
